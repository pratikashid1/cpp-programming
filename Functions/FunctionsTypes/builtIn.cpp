#include <iostream>
#include <bits/stdc++.h>
using namespace std;

int main() {

    // Square root sqrt()
    double num = 225.00;
    cout << "Square root: " << sqrt(num) << endl;

    // Absolute valuse abs()
    double num1 = -123.44;
    cout << "Absolute value: " << abs(num1) << endl;

    // Getline getline()
    string name;
    cout << "Your name: ";
    getline(cin, name);
    cout << "Hello, " << name << endl;

    return 0;
}